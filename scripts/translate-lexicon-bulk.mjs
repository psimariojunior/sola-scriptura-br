function translateFile(filePath) {
  const content = readFileSync(filePath, 'utf8');
  let changes = 0;
  
  let result = content;
  for (const [pattern, replacement] of PATTERNS) {
    const before = result;
    result = result.replace(pattern, replacement);
    if (result !== before) {
      changes++;
    }
  }
  
  writeFileSync(filePath, result, 'utf8');
  return changes;
}

