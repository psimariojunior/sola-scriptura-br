export function buscarUsosPorLivroNT(livro: string): UsoNTnoOT[] {
  const livroLower = livro.toLowerCase();
  return USOS_NT_NOT.filter(
    (u) =>
      u.novTestamentoLivro.toLowerCase() === livroLower ||
      u.novTestamentoRef.toLowerCase().startsWith(livroLower),
  );
}

export function buscarUsosPorLivroAT(livro: string): UsoNTnoOT[] {
  const livroLower = livro.toLowerCase();
  return USOS_NT_NOT.filter(
    (u) =>
      u.antigoTestamentoLivro.toLowerCase() === livroLower ||
      u.antigoTestamentoRef.toLowerCase().startsWith(livroLower),
  );
}

export function buscarUsosPorCategoria(
  categoria: UsoNTnoOT["categoria"],
): UsoNTnoOT[] {
  return USOS_NT_NOT.filter((u) => u.categoria === categoria);
}

