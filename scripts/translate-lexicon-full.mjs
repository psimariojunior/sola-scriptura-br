// Função para traduzir uma definição
function translateDefinition(def, palavra = '') {
  if (!def) return def;
  
  // Se já está em português (contém acentos PT), retorna como está
  if (/[ãõêôçáéíóúâêîôûà]/i.test(def) && 
      !/\b(properly|i\.e\.|figuratively|literally|specially|by implication|concrete|abstract)\b/i.test(def)) {
    return def;
  }
  
  let result = def;
  
  // Aplicar traduções do dicionário (ordenado por comprimento, mais longo primeiro)
  const sortedEntries = Object.entries(DICT_EN_PT).sort((a, b) => b[0].length - a[0].length);
  
  for (const [en, pt] of sortedEntries) {
    if (result.toLowerCase().includes(en.toLowerCase())) {
      const regex = new RegExp(en.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi');
      result = result.replace(regex, pt);
    }
  }
  
  // Se a definição ainda contém muitas palavras em inglês, retornar original
  const englishWords = result.match(/\b[a-z]{4,}\b/g) || [];
  const ptWords = result.match(/\b[a-záéíóúâêîôûãõç]{4,}\b/g) || [];
  
  // Se mais de 50% ainda são palavras inglesas, retorna a original com标记
  if (englishWords.length > ptWords.length * 0.5 && englishWords.length > 3) {
    return def; // Manter original, tradução automática insuficiente
  }
  
  return result;
}

// Processar hebraico
function processHebrew() {
  const filePath = join(process.cwd(), 'src/data/lexicon/hebraico.ts');
  const content = readFileSync(filePath, 'utf8');
  
  // Contar entradas que precisam de tradução
  let needsTranslation = 0;
  let translated = 0;
  
  const lines = content.split('\n');
  const newLines = [];
  
  for (const line of lines) {
    const match = line.match(/definicao:\s*["'](.+?)["']/);
    if (match) {
      const definicao = match[1];
      
      // Verificar se está em inglês
      if (/\b(properly|i\.e\.|figuratively|literally|specially|by implication|concrete|abstract|wander|perish|destroy)\b/i.test(definicao) &&
          !/[ãõêôçáéíóúâêîôûà]/i.test(definicao)) {
        needsTranslation++;
        const translated_def = translateDefinition(definicao);
        if (translated_def !== definicao) {
          translated++;
          newLines.push(line.replace(definicao, translated_def));
          continue;
        }
      }
    }
    newLines.push(line);
  }
  
  writeFileSync(filePath, newLines.join('\n'), 'utf8');
  
  console.log(`Hebraico: ${needsTranslation} entradas precisavam de tradução, ${translated} traduzidas`);
  return { needsTranslation, translated };
}

// Processar grego
function processGreek() {
  const filePath = join(process.cwd(), 'src/data/lexicon/grego.ts');
  const content = readFileSync(filePath, 'utf8');
  
  let needsTranslation = 0;
  let translated = 0;
  
  const lines = content.split('\n');
  const newLines = [];
  
  for (const line of lines) {
    const definicaoMatch = line.match(/definicao:\s*["'](.+?)["']/);
    const resumidaMatch = line.match(/definicaoResumida:\s*["'](.+?)["']/);
    
    let newLine = line;
    
    if (definicaoMatch) {
      const definicao = definicaoMatch[1];
      if (/\b(properly|i\.e\.|figuratively|literally|specially|by implication|to work|well-doing|virtue|indignation|announcement|receptacle)\b/i.test(definicao) &&
          !/[ãõêôçáéíóúâêîôûà]/i.test(definicao)) {
        needsTranslation++;
        const translated_def = translateDefinition(definicao);
        if (translated_def !== definicao) {
          translated++;
          newLine = newLine.replace(definicao, translated_def);
        }
      }
    }
    
    if (resumidaMatch) {
      const resumida = resumidaMatch[1];
      if (/\b(properly|i\.e\.|figuratively|literally|specially|to work|well-doing|virtue|indignation|announcement)\b/i.test(resumida) &&
          !/[ãõêôçáéíóúâêîôûà]/i.test(resumida)) {
        const translated_res = translateDefinition(resumida);
        if (translated_res !== resumida) {
          newLine = newLine.replace(resumida, translated_res);
        }
      }
    }
    
    newLines.push(newLine);
  }
  
  writeFileSync(filePath, newLines.join('\n'), 'utf8');
  
  console.log(`Grego: ${needsTranslation} entradas precisavam de tradução, ${translated} traduzidas`);
  return { needsTranslation, translated };
}

