export function findPrecomputedAnswer(question: string): string | null {
  const q = question.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');

  for (const [key, answer] of Object.entries(precomputedAnswers)) {
    const normalizedKey = key.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    if (q.includes(normalizedKey) || normalizedKey.split(' ').every(w => q.includes(w))) {
      return answer;
    }
  }

  return null;
}
