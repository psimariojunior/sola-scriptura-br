// Detect if a definition is a proper noun (name) - these should be kept as-is
function isProperNoun(line) {
  const palavraMatch = line.match(/palavra: '([^']*)'/);
  if (!palavraMatch) return false;
  const palavra = palavraMatch[1];
  // Hebrew names typically start with capital letter in transliteration
  // and have frequency < 50 (common words have higher frequency)
  const freqMatch = line.match(/frequencia: (\d+)/);
  const freq = freqMatch ? parseInt(freqMatch[1]) : 0;
  
  // Proper nouns: capitalized name, low frequency
  if (/^[A-Z]/.test(palavra) && freq < 50) return true;
  // Also check if definition looks like a name (single word, capitalized)
  const defMatch = line.match(/definicao: '([^']*)'/);
  if (defMatch) {
    const def = defMatch[1];
    if (/^[A-Z][a-z]+$/.test(def) && def.length > 2 && freq < 30) return true;
  }
  return false;
}

// Check if definition contains English
function hasEnglish(def) {
  return /\b(the|and|of|to|in|a|is|or|for|with|from|by|that|this|it|not|be|have|has|had|do|will|would|can|could|should|shall|may|might|but|if|when|which|who|where|how|what|properly|by implication|i\.e\.|figuratively|literally|concrete|abstract|hence|also|probably|perhaps|figuratively|specially|then|than|also)\b/i.test(def);
}

