const newComments = [];
for (const [bookAbbr, bookVerses] of Object.entries(extraVerses)) {
  for (const [chapter, verse, tipo, texto] of bookVerses) {
    const key = `${bookAbbr}:${chapter}:${verse}`;
    if (!existingRefs.has(key)) {
      const author = theologians[Math.floor(Math.random() * theologians.length)];
      const escapedTexto = texto.replace(/'/g, "\\'");
      const escapedAuthor = author.replace(/'/g, "\\'");
      newComments.push(`add('${bookAbbr}', ${chapter}, ${verse}, '${escapedAuthor}', '${escapedTexto}', '${tipo}');`);
      existingRefs.add(key);
    }
  }
}

const exportIdx = content.indexOf('export function');
if (exportIdx === -1) {
  console.error('Could not find "export function"');
  process.exit(1);
}

const newContent = content.substring(0, exportIdx) + '\n// === Novos comentarios batch 1 - supplemento (PT-BR) ===\n' + newComments.join('\n') + '\n\n' + content.substring(exportIdx);
