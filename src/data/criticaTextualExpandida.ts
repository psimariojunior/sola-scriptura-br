export function obterVarianteExpandida(livro: string, capitulo: number, versiculo: number): VarianteTextualExpandida | undefined {
  return variantesTextuaisExpandidas.find(
    (v) => v.livro === livro && v.capitulo === capitulo && v.versiculo === versiculo
  );
}

export function obterVariantesPorLivroExpandida(livro: string): VarianteTextualExpandida[] {
  return variantesTextuaisExpandidas.filter((v) => v.livro === livro);
}

export function obterVariantesPorImportancia(importancia: 'alta' | 'media' | 'baixa'): VarianteTextualExpandida[] {
  return variantesTextuaisExpandidas.filter((v) => v.importancia === importancia);
}
